#!/bin/bash
# build.sh -- 5 Card Stud for the Odyssey 2: build/5card.bin, a protocol 2
# (APPBANK) image -- the fixed half ($400-$7FF) and NPAGES pages of 2K.
#
#   ./build.sh                          the image, against the live server
#   ENDPOINT=http://host:port/ ./build.sh
#   SPIKE=1 ./build.sh                  the table engine's test pattern
#   AUTOPLAY=1 ./build.sh               plays itself (test/soak runs)
#   DEVTABLES=1 ./build.sh              lists the server's hidden dev tables
#   NAMEW= ... PADN=      the table's layout and timing (src/equ.inc)
#
# Needs Macroassembler AS (~/asl/asl and p2bin, or ASL=/P2BIN=).
set -e
HERE="$(cd "$(dirname "$0")" && pwd)"
OUT="${OUT:-$HERE/build}"
ASL="${ASL:-$HOME/asl/asl}"
P2BIN="${P2BIN:-$HOME/asl/p2bin}"
SPIKE="${SPIKE:-0}"
AUTOPLAY="${AUTOPLAY:-0}"
DEVTABLES="${DEVTABLES:-0}"
if [ "$SPIKE" = 1 ]; then NPAGES=2; else NPAGES="${NPAGES:-7}"; fi
mkdir -p "$OUT"

python3 "$HERE/tools/checkflags.py" "$HERE"/src/*.inc
python3 "$HERE/tools/mkcharmap.py" "$OUT/charmap.inc"
# The server. Its routes follow it directly, so it ends in '/'.
ENDPOINT="${ENDPOINT:-https://5card.carr-designs.com/}"
case "$ENDPOINT" in
  */) ;;
  *) ENDPOINT="$ENDPOINT/" ;;
esac
printf '; GENERATED by build.sh -- do not edit.\nu_endp: db "%s",0\n' "$ENDPOINT" > "$OUT/endpoint.inc"
{
  echo "; GENERATED by build.sh -- do not edit."
  echo "SPIKE equ $SPIKE"
  echo "AUTOPLAY equ $AUTOPLAY"
  echo "DEVTABLES equ $DEVTABLES"
  for v in NAMEW NAMEX CARDX Y_T0 Y_ROW0 Y_T1 LEAD SEPA SEPAF SEPB SEPBF PADN; do
    [ -n "${!v:-}" ] && echo "$v equ ${!v}"
  done
  true
} > "$OUT/flags.inc"
cp "$HERE"/src/*.inc "$HERE/g7000.h" "$HERE/5card.a48" "$OUT/"

parts=""
for p in $(seq 0 $((NPAGES-1))); do
  printf '; GENERATED by build.sh -- do not edit.\nPAGE equ %d\nNPAGES equ %d\n    include "5card.a48"\n' \
    "$p" "$NPAGES" > "$OUT/5card_p$p.a48"
  ( cd "$OUT" && "$ASL" -q -L -U "5card_p$p.a48" \
      && "$P2BIN" "5card_p$p.p" "5card_pg$p.bin" -r 0x800-0xFFF -l 0 >/dev/null \
      && "$P2BIN" "5card_p$p.p" "5card_fx$p.bin" -r 0x400-0x7FF -l 0 >/dev/null )
  python3 "$HERE/tools/checkobj.py" "$OUT/5card_p$p.p"
  python3 "$HERE/tools/checklayout.py" "$OUT/5card_p$p.lst"
  python3 "$HERE/tools/checkmb.py" "$OUT/5card_p$p.lst" >/dev/null
  python3 "$HERE/tools/checkpage.py" "$OUT/5card_p$p.lst"
  # Every page carries the fixed half; they have to be the same bytes.
  cmp -s "$OUT/5card_fx0.bin" "$OUT/5card_fx$p.bin" \
    || { echo "build.sh: page $p assembled a different fixed half" >&2; exit 1; }
  parts="$parts $OUT/5card_pg$p.bin"
done
# The stack is 8 levels and wraps silently: interrupts plus the deepest main
# chain have to fit.
python3 "$HERE/tools/checkstack.py" $(for p in $(seq 0 $((NPAGES-1))); do echo "$OUT/5card_p$p.lst"; done) >/dev/null
cat "$OUT/5card_fx0.bin" $parts > "$OUT/5card.bin"
size=$(wc -c < "$OUT/5card.bin")
[ "$size" -eq $((1024 + 2048 * NPAGES)) ] \
  || { echo "build.sh: 5card.bin is $size bytes" >&2; exit 1; }
echo "build/5card.bin: $size bytes, $NPAGES pages"
if [ "$SPIKE" = 1 ]; then echo "  (the SPIKE test pattern)"; fi
