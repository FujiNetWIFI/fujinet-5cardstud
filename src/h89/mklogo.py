# Letters that need diagonals are drawn in cells instead, with the H19's
# triangles: three rows of the characters in CELL below.
G_TRI_UL, G_TRI_UR = 0x12, 0x1F
CELL = {
    ' ': 0x20,
    '█': REV | 0x20,
    '▀': G_HALF_TOP,
    '▄': REV | G_HALF_TOP,
    '◤': G_TRI_UL,
    '◥': G_TRI_UR,
    '◢': REV | G_TRI_UL,
    '◣': REV | G_TRI_UR,
}

CELLFONT = {
    'X': ["█◣ ◢█",
          " ███ ",
          "█◤ ◥█"],
    'A': [" ◢█◣ ",
          "◢▄▄▄◣",
          "█   █"],
    'M': ["█◣ ◢█",
          "█◥▄◤█",
          "█   █"],
    'R': ["█▀▀▀◣",
          "█▄▄▄◤",
          "█  ◥◣"],
}
WIDTH = 80


def letterCells(ch):
    if ch in CELLFONT:
        return [[CELL[c] for c in row] for row in CELLFONT[ch]]
    rows = FONT[ch]
    out = []
    for cy in range(0, 6, 2):
        line = []
        for cx in range(0, len(rows[0]), 2):
            key = tuple(int(rows[cy + dy][cx + dx] == '#')
                        for dy in (0, 1) for dx in (0, 1))
            if key not in QUAD:
                sys.exit("mklogo: no H19 character for the pixels of %r at "
                         "column %d, row %d" % (ch, cx, cy))
            line.append(QUAD[key])
        out.append(line)
    return out


def cells(word):
    out = [[], [], []]
    for n, ch in enumerate(word):
        for r, line in enumerate(letterCells(ch)):
            out[r] += ([0x20] if n else []) + line   # a cell between letters
    return out


# Each logo line: the word and its top screen row
LINES = [("5 CARD", 2), ("STUD", 6)]

print("/* Generated by src/h89/mklogo.py -- do not edit. */")
print("/* Title logo as runs of H19 cell codes: row, column, length, codes;")
print("   0xFF ends it. */")
print("#ifndef H89_LOGO_H")
print("#define H89_LOGO_H")
print()
print("static const unsigned char logo[] = {")
for word, top in LINES:
    grid = cells(word)
    x = (WIDTH - len(grid[0])) // 2
    for r, line in enumerate(grid):
        print("    %d, %d, %d," % (top + r, x, len(line)))
        for i in range(0, len(line), 12):
            print("        " + " ".join("0x%02X," % c for c in line[i:i + 12]))
print("    0xFF")
print("};")
print()
print("#endif /* H89_LOGO_H */")
